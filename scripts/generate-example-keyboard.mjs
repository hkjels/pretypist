import { readFileSync, writeFileSync } from "node:fs";
import { RoundedBoxGeometry } from "three/addons/geometries/RoundedBoxGeometry.js";

const output = new URL("../resources/layout-sources/one-piece-example/", import.meta.url);
const letters = row => [...row].map(letter => [letter, letter, `Key${letter.toUpperCase()}`]);
const rows = [
  letters("qwertyuiop"),
  [...letters("asdfghjkl"), ["quote", "'", "Quote"]],
  [...letters("zxcvbnm"), ["comma", ",", "Comma"], ["period", ".", "Period"], ["slash", "/", "Slash"]],
  [["space", " ", "Space"]],
];
const metres = mm => mm / 1000;
const pitch = 19;
const keys = rows.flatMap((row, r) => row.map(([id, text, code], c) => ({
  id, text, code, row: r, column: c,
  legend: id === "space" ? "Space" : text.toUpperCase(),
  node: `key_${id}`,
  translation: [metres((c - (row.length - 1) / 2) * pitch + [-4.75, 0, 4.75, 0][r]),
    metres(14), metres((r - 1.5) * pitch)],
})));

const layout = `;; Generated by scripts/generate-example-keyboard.mjs.
{:pretypist/format-version 1
 :package/id "one-piece-example"
 :package/name "One-Piece Example"
 :package/revision 1
 :package/license "MIT"
 :layout/languages #{:en :nb}
 :layout/default-layer :base
 :layout/layer-order [:base]
 :model {:file "model.glb"
         :root-node "compact_board"
         :case-nodes ["compact_case"]
         :units :meters
         :up-axis :y
         :material-policy :preserve}
 :keys
 [${keys.map(({ id, node, row, column, code }, index) =>
    `{:id :${id} :index ${index} :node "${node}" :row ${row} :column ${column} :observed-codes ["${code}"]}`).join("\n  ")}]
 :layers
 {:base {:name "Base"
         :bindings
         {${keys.map(({ id, legend, text }) =>
    `:${id} {:legend ${JSON.stringify(legend)} :actions {:tap [:text ${JSON.stringify(text)}]}}`).join("\n          ")}}}}}
`;

const gltf = {
  asset: { version: "2.0", generator: "PRETYPIST one-piece example" },
  scene: 0,
  scenes: [{ nodes: [0] }],
  nodes: [
    { name: "compact_board", children: Array.from({ length: keys.length + 1 }, (_, i) => i + 1) },
    { name: "compact_case", mesh: 0, translation: [0, metres(5), 0] },
    ...keys.map(({ node, id, translation }) => ({ name: node, translation, mesh: id === "space" ? 2 : 1 })),
  ],
  materials: [
    { name: "Slate case", pbrMetallicRoughness: { baseColorFactor: [0.038, 0.061, 0.086, 1], metallicFactor: 0, roughnessFactor: 0.68 } },
    { name: "Warm keycaps", pbrMetallicRoughness: { baseColorFactor: [0.58, 0.52, 0.43, 1], metallicFactor: 0, roughnessFactor: 0.59 } },
    { name: "Copper spacebar", pbrMetallicRoughness: { baseColorFactor: [0.6, 0.22, 0.09, 1], metallicFactor: 0, roughnessFactor: 0.63 } },
  ],
  meshes: [], accessors: [], bufferViews: [], buffers: [],
};

const chunks = [];
let byteOffset = 0;
for (const [width, height, depth, radius] of [[209, 10, 85, 3], [17.2, 6, 17.2, 1.4], [93.2, 6, 17.2, 1.4]]) {
  const geometry = new RoundedBoxGeometry(metres(width), metres(height), metres(depth), 1, metres(radius));
  geometry.computeBoundingBox();
  const attributes = {};
  for (const [name, semantic] of [["position", "POSITION"], ["normal", "NORMAL"]]) {
    const { array, count } = geometry.getAttribute(name);
    const bytes = Buffer.from(array.buffer, array.byteOffset, array.byteLength);
    const bufferView = gltf.bufferViews.push({ buffer: 0, byteOffset, byteLength: bytes.length, target: 34962 }) - 1;
    chunks.push(bytes);
    byteOffset += bytes.length;
    const bounds = name === "position" ? { min: geometry.boundingBox.min.toArray(), max: geometry.boundingBox.max.toArray() } : {};
    attributes[semantic] = gltf.accessors.push({ bufferView, componentType: 5126, count, type: "VEC3", ...bounds }) - 1;
  }
  gltf.meshes.push({ primitives: [{ attributes, material: gltf.meshes.length }] });
  geometry.dispose();
}
gltf.buffers.push({ byteLength: byteOffset });

const json = Buffer.from(JSON.stringify(gltf));
const paddedJson = Buffer.concat([json, Buffer.alloc((4 - json.length % 4) % 4, 32)]);
const binary = Buffer.concat(chunks);
const header = Buffer.alloc(20);
for (const [index, value] of [0x46546c67, 2, 28 + paddedJson.length + binary.length, paddedJson.length, 0x4e4f534a].entries()) {
  header.writeUInt32LE(value, index * 4);
}
const binHeader = Buffer.alloc(8);
binHeader.writeUInt32LE(binary.length, 0);
binHeader.writeUInt32LE(0x004e4942, 4);
const model = Buffer.concat([header, paddedJson, binHeader, binary]);

for (const [filename, bytes] of [["layout.edn", Buffer.from(layout)], ["model.glb", model]]) {
  const destination = new URL(filename, output);
  if (process.argv.includes("--check")) {
    if (!readFileSync(destination).equals(bytes)) throw new Error(`Example ${filename} is stale; run npm run package:example.`);
  } else {
    writeFileSync(destination, bytes);
  }
}
console.log(`One-Piece Example: ${keys.length} keys, ${model.length} model bytes.`);
